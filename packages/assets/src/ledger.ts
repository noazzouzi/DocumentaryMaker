/** mm:ss (h:mm:ss above an hour); `round` = floor for range starts, ceil for range ends (the range always covers the clip). */
const tc = (ms: number, round: (x: number) => number = Math.round) => {
  const s = Math.max(0, round(ms / 1000));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${ss}` : `${String(m).padStart(2, "0")}:${ss}`;
};

/** Human-readable transformations applied by the conform recipe. */
export function transformationsOf(a: FrozenAsset): string[] {
  const out: string[] = [];
  const r = a.conform.recipe;
  if (r === "image-v1" || r === "proc-image-v1") out.push("exif-rotate", `resize long edge ≤ 2880 (${a.width}×${a.height})`, a.ext === "png" ? "png" : "jpeg q90");
  if (r.startsWith("video") || r === "proc-video-v1" || r === "clip-v1") {
    if (a.conform.sourceInMs !== null && a.conform.sourceOutMs !== null) out.push(`trim ${tc(a.conform.sourceInMs, Math.floor)}–${tc(a.conform.sourceOutMs, Math.ceil)}`);
    out.push(`transcode h264 cfr ${a.fps ?? "?"}`, a.hasAudio ? "aac 192k" : "muted");
  }
  if (r === "clip-v1" || r === "audio-norm-v1") out.push(`loudnorm ${a.lufs ?? -18} LUFS`);
  if (r.startsWith("proc-")) out.unshift("generated procedurally");
  return out;
}

export function providerOfAsset(a: FrozenAsset): AssetProviderId {
  if (a.candidate) return a.candidate.provider;
  if (a.declaration) return "local";
  return "procedural";
}

export function ledgerEntryFor(a: FrozenAsset): LedgerEntry {
  const license = licenseOfAsset(a);
  const c = a.candidate;
  const provider = providerOfAsset(a);
  const title = c?.title ?? (isPipelineGenerated(a) ? `Procedural ${a.kind} (${a.conform.recipe})` : a.declaration ? a.declaration.note || "Imported media" : "Media");
  const author = cleanAuthor(c?.author?.name ?? (a.declaration?.author || null));
  const sourcePageUrl = c?.sourcePageUrl ?? a.declaration?.url ?? "";
  const attr = license.attributionText ?? attributionText({ title, author, license, sourcePageUrl: sourcePageUrl || null });
  return LedgerEntry.parse({
    assetId: a.id, provider, title, sourcePageUrl, fileUrl: c?.downloadUrl ?? "", author, license: { ...license, attributionText: attr },
    attributionText: attr, retrievedAt: c?.retrievedAt ?? a.frozenAt ?? nowIso(), youtube: c?.youtube ?? null, declaration: a.declaration,
    transformations: transformationsOf(a),
  });
}

/** Ledger for the given assets (sorted by assetId; deterministic). */
export function buildLedger(assets: Iterable<FrozenAsset>): Ledger {
  const entries = [...assets].map(ledgerEntryFor).sort((a, b) => (a.assetId < b.assetId ? -1 : a.assetId > b.assetId ? 1 : 0));
  return { schemaVersion: 1, entries };
}

