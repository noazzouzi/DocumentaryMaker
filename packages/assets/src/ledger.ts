function licText(l: LicenseInfo): string {
  return `${LICENSE_LABEL[l.code]}${l.version ? ` ${l.version}` : ""}`;
}
const isSa = (l: LicenseInfo) => l.code.endsWith("-SA") || l.restrictions.includes("sa");

/** Canonical Creative Commons URL of a licence (https, no "deed.xx", trailing slash), built from the code and version when
 *  the provider gave none; other URLs are kept as given; null when there is none. */
export function licenseUrl(l: Pick<LicenseInfo, "code" | "version" | "url">): string | null {
  const given = (l.url ?? "").trim();
  if (given !== "") {
    const m = /^https?:\/\/creativecommons\.org\/((?:licenses|publicdomain)\/[a-z-]+(?:\/\d+(?:\.\d+)?)?)/i.exec(given);
    return m ? `https://creativecommons.org/${m[1]!.toLowerCase()}/` : given;
  }
  if (l.code === "CC0") return "https://creativecommons.org/publicdomain/zero/1.0/";
  if (l.code === "PDM") return "https://creativecommons.org/publicdomain/mark/1.0/";
  if (l.code.startsWith("CC-BY") && l.version) return `https://creativecommons.org/licenses/${l.code.slice(3).toLowerCase()}/${l.version}/`;
  return null;
}

/** Kind of media a ledger entry describes, from its transformations (a transcode → video). */
const isVideoEntry = (e: { transformations?: readonly string[] }) => (e.transformations ?? []).some((t) => t.startsWith("transcode"));

/** `"<title>" by <author> — <licence> (<licence URL>) — <source> — <modified note>`: every licence with a known deed carries
 *  its link, and every visual says how it was changed (stills are cropped, colour-graded and animated; videos trimmed and
 *  colour-graded) — CC BY* licences require it, and it is honest for public-domain works too. */
function line(e: { title: string; author: string | null; license: LicenseInfo; sourcePageUrl: string; transformations?: readonly string[] }, lang: Lang, visual = true): string {
  const t = e.title.trim() || "Untitled";
  const author = cleanAuthor(e.author);
  const by = lang === "fr" ? "par" : "by";
  const url = licenseUrl(e.license);
  const lic = `${licText(e.license)}${url ? ` (${url})` : ""}`;
  const modified = visual ? ` — ${isVideoEntry(e) ? T[lang].modifiedVideo : T[lang].modified}` : "";
  return `"${t}"${author ? ` ${by} ${author}` : ""} — ${lic}${e.sourcePageUrl ? ` — ${e.sourcePageUrl}` : ""}${modified}`;
}

const ARCHIVAL = new Set<string>(["wikimedia", "loc", "internet-archive", "nasa", "openverse"]);
const STOCK = new Set<string>(["pexels", "pixabay"]);

export function buildCredits(i: { ledger: Ledger; usage: UsageDoc; lang: Lang; voice: VoiceTrack | null; music: MusicDoc; sfx: readonly SfxEntry[] }): string {
  const t = T[i.lang];
  const used = new Set(i.usage.usage.map((u) => u.assetId));
  const entries = i.ledger.entries.filter((e) => used.has(e.assetId));
  const groups: { title: string; lines: string[] }[] = [];
  const add = (title: string, lines: string[]) => {
    const uniq = [...new Set(lines)].sort((a, b) => a.localeCompare(b));
    if (uniq.length > 0) groups.push({ title, lines: uniq });
  };
  const ai = entries.filter((e) => e.license.code === "AI-GENERATED");
  const rest = entries.filter((e) => e.license.code !== "AI-GENERATED");
  const ln = (e: Ledger["entries"][number]) => line(e, i.lang, true);
  add(t.archival, rest.filter((e) => ARCHIVAL.has(e.provider)).map(ln));
  add(t.stock, rest.filter((e) => STOCK.has(e.provider)).map((e) => `${ln(e)}${e.provider === "pexels" ? " (Pexels)" : " (Pixabay)"}`));
  add(t.web, rest.filter((e) => e.provider === "brave").map(ln));
  const isClip = (e: Ledger["entries"][number]) => e.provider === "youtube" || e.youtube !== null || e.license.code === "YOUTUBE-FAIR-USE";
  add(t.clips, rest.filter(isClip).map((e) => {
    const y = e.youtube;
    const span = y && y.startMs !== null && y.endMs !== null ? ` [${tc(y.startMs, Math.floor)}–${tc(y.endMs, Math.ceil)}]` : "";
    return `"${e.title}" — ${y?.channel ?? e.author ?? "unknown channel"} — ${y?.url ?? e.sourcePageUrl}${span}`;
  }));
  // Music: tracks used by this language's timeline.
  const musicLines: string[] = [];
  for (const tr of i.music.tracks.filter((m) => used.has(m.assetId))) {
    musicLines.push(tr.source === "procedural" ? t.procMusic : line({ title: tr.title, author: null, license: tr.license, sourcePageUrl: "" }, i.lang, false));
  }
  add(t.music, musicLines);
  const sfxUsed = i.sfx.filter((s) => used.has(s.assetId));
  add(t.sfx, sfxUsed.map((s) => (s.pack === "procedural" ? t.procSfx : s.license.attributionText ?? `${s.pack}: ${s.category} — ${licText(s.license)}`)));
  // Voice (from the active take's licence).
  const voiceLines: string[] = [];
  let syntheticVoice = false;
  if (i.voice) {
    const v = i.voice;
    syntheticVoice = v.provider !== "recording";
    const kind = v.provider === "recording" ? t.recording : t.syntheticVoice;
    voiceLines.push(`${v.provider} — ${v.voiceId} (${kind}) — ${licText(v.license)}${v.license.attributionText ? ` — ${v.license.attributionText}` : ""}`);
    if (v.provider === "elevenlabs" && (v.license.restrictions.includes("nc") || !v.license.commercialOk)) voiceLines.push(t.elevenFree);
  }
  add(t.voice, voiceLines);
  add(t.ai, ai.map((e) => `${ln(e)} (AI)`));
  add(t.own, rest.filter((e) => e.provider === "local" && !isClip(e)).map((e) => (e.declaration?.kind === "own-work" ? `"${e.title}" — ${e.author ?? ""} (${LICENSE_LABEL["USER-OWNED"]})` : ln(e))));
  if (rest.some((e) => e.provider === "procedural")) add(t.procedural, [t.procLine]);
  add(t.fonts, BUILTIN_FONTS.map((f) => `${f.family} — SIL Open Font License 1.1`));

  const out: string[] = [`# ${t.title}`, ""];
  for (const g of groups) {
    out.push(`## ${g.title}`, "");
    for (const l of g.lines) out.push(`- ${l}`);
    out.push("");
  }
  // Compact block to paste into the YouTube description (no fonts, no procedural lines).
  const yt: string[] = [];
  for (const g of groups) {
    if (g.title === t.fonts || g.title === t.procedural) continue;
    for (const l of g.lines) if (l !== t.procMusic && l !== t.procSfx) yt.push(l);
  }
  out.push(`## ${t.ytBlock}`, "", "```", ...(yt.length > 0 ? yt : ["—"]), "```", "");
  if (ai.length > 0 || syntheticVoice) out.push(`> ${t.synthetic}`, "");
  if (entries.some((e) => isSa(e.license) && e.license.code.startsWith("CC-BY"))) out.push(`> ${t.shareAlike}`, "");
  return out.join("\n");
}
